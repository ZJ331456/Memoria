"""Host-facing contracts. No SQLite connection or application runtime is required."""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from .records import MemorySearch
from .library import SourceInput


@runtime_checkable
class MemoryReadPort(Protocol):
    async def access(self, request): ...
    async def answer(self, request): ...
    def revalidate_answer(self, request, result, *, answer=None): ...
    async def search(self, request: MemorySearch, *, capture=None, retrieval_query=None): ...
    def read(self, domain, source_id: str, *, session_id: str | None = None): ...
    def dependency_valid(self, dependency: dict, *, session_id: str | None = None) -> bool: ...


@runtime_checkable
class MemoryWritePort(Protocol):
    def ingest(self, source: SourceInput): ...
    def ingest_file(self, **values): ...
    def record_message(self, session_id, role, content, *, source_time=None): ...
